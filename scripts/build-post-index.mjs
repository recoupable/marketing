import { readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** Generate publication facts only; editorial plans stay outside this index. */
export function renderPublishedPostsIndex(posts) {
  if (!Array.isArray(posts))
    throw new Error("Published posts must be an array");
  const slugs = new Set();
  const cell = (value) => value.replace(/\|/g, "\\|").replace(/[\r\n]+/g, " ");
  for (const post of posts) {
    if (
      !post ||
      typeof post.slug !== "string" ||
      !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(post.slug) ||
      ![post.title, post.date, post.category].every(
        (value) => typeof value === "string" && value.trim().length > 0,
      )
    ) {
      throw new Error(
        "Each published post needs a canonical slug, title, date and category",
      );
    }
    if (slugs.has(post.slug))
      throw new Error(`Duplicate published slug: ${post.slug}`);
    slugs.add(post.slug);
  }
  const rows = [...posts]
    .sort(
      (a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug),
    )
    .map(
      (post) =>
        `| ${cell(post.date)} | [${cell(post.title).replace(/[\[\]]/g, "\\$&")}](/blog/${post.slug}) | ${cell(post.category)} | published |`,
    );
  return [
    "# Published posts",
    "",
    "<!-- Generated by scripts/build-post-index.mjs. Do not edit by hand. -->",
    "",
    "Source: `content/blog/posts.json`, also used by the blog pages, feed and agent content.",
    "Every entry in that source is public when deployed; this inventory does not verify a live deployment.",
    "Drafts and publication proposals belong outside that source until approved.",
    "Regenerate with `pnpm posts:build`; verify with `pnpm posts:check`.",
    "",
    `Published source entries: **${posts.length}**.`,
    "",
    "| Date | Title | Category | Status |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
    "## Historical planning notes",
    "",
    "The former hand-maintained index and topic gaps are preserved in [the October 20, 2026 archive](archive/index-2026-10-20.md).",
    "They describe earlier editorial planning and are not a current publication inventory or current gap assessment.",
    "Legacy MDX files in this directory do not drive the website.",
    "",
  ].join("\n");
}

if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  if (process.argv.slice(2).some((argument) => argument !== "--check")) {
    throw new Error("Usage: node scripts/build-post-index.mjs [--check]");
  }
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const source = JSON.parse(
    readFileSync(resolve(root, "content/blog/posts.json"), "utf8"),
  );
  const destination = resolve(root, "content/posts/INDEX.md");
  const expected = renderPublishedPostsIndex(source);
  if (process.argv.includes("--check")) {
    if (readFileSync(destination, "utf8") !== expected) {
      throw new Error(
        "Published post inventory is stale; run pnpm posts:build",
      );
    }
  } else {
    writeFileSync(destination, expected);
  }
}
